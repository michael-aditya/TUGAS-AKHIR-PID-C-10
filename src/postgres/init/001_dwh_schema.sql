CREATE TABLE IF NOT EXISTS dim_machine (
    machine_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id VARCHAR(16) NOT NULL UNIQUE,
    model VARCHAR(64) NOT NULL,
    production_line VARCHAR(32) NOT NULL,
    installation_date DATE NOT NULL,
    service_interval_days SMALLINT NOT NULL CHECK (service_interval_days > 0),
    last_service_date DATE NOT NULL,
    vibration_warning_threshold_mms NUMERIC(5, 2) NOT NULL,
    vibration_critical_threshold_mms NUMERIC(5, 2) NOT NULL,
    spindle_temp_warning_threshold_c NUMERIC(5, 1) NOT NULL,
    spindle_temp_critical_threshold_c NUMERIC(5, 1) NOT NULL,
    CONSTRAINT chk_dim_machine_vibration_thresholds CHECK (
        vibration_warning_threshold_mms < vibration_critical_threshold_mms
    ),
    CONSTRAINT chk_dim_machine_temperature_thresholds CHECK (
        spindle_temp_warning_threshold_c < spindle_temp_critical_threshold_c
    ),
    CONSTRAINT uq_dim_machine_key_id UNIQUE (machine_key, machine_id)
);

CREATE TABLE IF NOT EXISTS dim_sensor (
    sensor_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id VARCHAR(24) NOT NULL UNIQUE,
    machine_key BIGINT NOT NULL,
    machine_id VARCHAR(16) NOT NULL,
    device_type VARCHAR(32) NOT NULL CHECK (
        device_type IN ('vibration', 'spindle', 'production_counter')
    ),
    engineering_unit VARCHAR(32) NOT NULL,
    normal_range_min NUMERIC(12, 3) NOT NULL,
    normal_range_max NUMERIC(12, 3) NOT NULL,
    sampling_rate_hz NUMERIC(6, 3) NOT NULL CHECK (sampling_rate_hz > 0),
    CONSTRAINT fk_dim_sensor_machine FOREIGN KEY (machine_key, machine_id)
        REFERENCES dim_machine (machine_key, machine_id)
        ON DELETE RESTRICT,
    CONSTRAINT chk_dim_sensor_normal_range CHECK (normal_range_min < normal_range_max)
);

CREATE INDEX IF NOT EXISTS idx_dim_sensor_machine_key ON dim_sensor (machine_key);

CREATE TABLE IF NOT EXISTS dim_time (
    time_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hour_start TIMESTAMPTZ NOT NULL UNIQUE,
    calendar_date DATE NOT NULL,
    year_number SMALLINT NOT NULL,
    month_number SMALLINT NOT NULL CHECK (month_number BETWEEN 1 AND 12),
    day_of_month SMALLINT NOT NULL CHECK (day_of_month BETWEEN 1 AND 31),
    day_of_week SMALLINT NOT NULL CHECK (day_of_week BETWEEN 0 AND 6),
    day_name VARCHAR(9) NOT NULL,
    hour_of_day SMALLINT NOT NULL CHECK (hour_of_day BETWEEN 0 AND 23),
    is_weekend BOOLEAN NOT NULL,
    production_shift VARCHAR(16) NOT NULL CHECK (
        production_shift IN ('Shift 1 Pagi', 'Shift 2 Sore', 'Shift 3 Malam')
    )
);

CREATE INDEX IF NOT EXISTS idx_dim_time_calendar_date ON dim_time (calendar_date);

CREATE TABLE IF NOT EXISTS dim_failure_type (
    failure_type_key SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    failure_code VARCHAR(40) NOT NULL UNIQUE,
    failure_name VARCHAR(80) NOT NULL,
    category VARCHAR(32) NOT NULL,
    default_severity VARCHAR(16) NOT NULL CHECK (
        default_severity IN ('INFO', 'WARNING', 'CRITICAL')
    ),
    description TEXT NOT NULL
);

