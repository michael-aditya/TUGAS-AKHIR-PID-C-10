    threshold_value DOUBLE PRECISION,
    window_end TIMESTAMPTZ NOT NULL,
    source_layer VARCHAR(16) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
