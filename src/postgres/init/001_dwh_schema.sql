CREATE TABLE IF NOT EXISTS fact_machine_hourly (
    machine_hourly_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_key BIGINT NOT NULL REFERENCES dim_machine (machine_key) ON DELETE RESTRICT,
    time_key BIGINT NOT NULL REFERENCES dim_time (time_key) ON DELETE RESTRICT,
    avg_vibration_mms NUMERIC(10, 4),
    max_vibration_mms NUMERIC(10, 4),
    avg_peak_g NUMERIC(10, 4),
    avg_spindle_temp_c NUMERIC(10, 4),
    max_spindle_temp_c NUMERIC(10, 4),
    avg_rpm NUMERIC(12, 3),
    avg_load_pct NUMERIC(8, 4),
    parts_produced NUMERIC(12, 3),
    parts_per_hour NUMERIC(12, 3),
    health_index NUMERIC(5, 2) CHECK (health_index BETWEEN 0 AND 100),
    rul_hours NUMERIC(12, 3),
    latest_status VARCHAR(16),
    reading_count INTEGER NOT NULL DEFAULT 0 CHECK (reading_count >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_fact_machine_hourly_machine_time UNIQUE (machine_key, time_key)
);

CREATE INDEX IF NOT EXISTS idx_fact_machine_hourly_time ON fact_machine_hourly (time_key);

CREATE TABLE IF NOT EXISTS fact_downtime_event (
    downtime_event_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_key BIGINT NOT NULL REFERENCES dim_machine (machine_key) ON DELETE RESTRICT,
    start_time_key BIGINT NOT NULL REFERENCES dim_time (time_key) ON DELETE RESTRICT,
    end_time_key BIGINT REFERENCES dim_time (time_key) ON DELETE RESTRICT,
    failure_type_key SMALLINT NOT NULL REFERENCES dim_failure_type (failure_type_key) ON DELETE RESTRICT,
    start_time TIMESTAMPTZ NOT NULL,
    end_time TIMESTAMPTZ,
    duration_minutes NUMERIC(12, 3) CHECK (duration_minutes IS NULL OR duration_minutes >= 0),
    status VARCHAR(16) NOT NULL DEFAULT 'OPEN',
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_fact_downtime_event_natural UNIQUE (machine_key, start_time, failure_type_key),
    CONSTRAINT chk_fact_downtime_event_range CHECK (end_time IS NULL OR end_time >= start_time)
);

CREATE INDEX IF NOT EXISTS idx_fact_downtime_event_machine ON fact_downtime_event (machine_key);
CREATE INDEX IF NOT EXISTS idx_fact_downtime_event_start ON fact_downtime_event (start_time_key);

CREATE TABLE IF NOT EXISTS fact_alert (
    alert_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_key BIGINT NOT NULL REFERENCES dim_machine (machine_key) ON DELETE RESTRICT,
    time_key BIGINT NOT NULL REFERENCES dim_time (time_key) ON DELETE RESTRICT,
    failure_type_key SMALLINT NOT NULL REFERENCES dim_failure_type (failure_type_key) ON DELETE RESTRICT,
    event_timestamp TIMESTAMPTZ NOT NULL,
    severity VARCHAR(16) NOT NULL CHECK (severity IN ('INFO', 'WARNING', 'CRITICAL')),
    metric_value NUMERIC(14, 4),
    threshold_value NUMERIC(14, 4),
    source_layer VARCHAR(16) NOT NULL CHECK (source_layer IN ('BATCH', 'STREAMING')),
    details JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_fact_alert_natural UNIQUE (
        machine_key,
        failure_type_key,
        event_timestamp,
        source_layer
    )
);

CREATE INDEX IF NOT EXISTS idx_fact_alert_machine_timestamp ON fact_alert (machine_key, event_timestamp);

CREATE TABLE IF NOT EXISTS dq_audit_summary (
    audit_summary_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id VARCHAR(64) NOT NULL,
    fault_type VARCHAR(40) NOT NULL,
    injected_count BIGINT NOT NULL DEFAULT 0 CHECK (injected_count >= 0),
    caught_count BIGINT NOT NULL DEFAULT 0 CHECK (caught_count >= 0),
    unmatched_count BIGINT NOT NULL DEFAULT 0 CHECK (unmatched_count >= 0),
    processed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    details JSONB NOT NULL DEFAULT '{}'::JSONB,
    CONSTRAINT uq_dq_audit_summary_run_fault UNIQUE (run_id, fault_type)
);

CREATE TABLE IF NOT EXISTS rt_window_metrics (
    machine_id VARCHAR(16) NOT NULL,
    window_size VARCHAR(8) NOT NULL CHECK (window_size IN ('1m', '10m')),
    window_start TIMESTAMPTZ NOT NULL,
    window_end TIMESTAMPTZ NOT NULL,
    avg_vibration_mms DOUBLE PRECISION,
    max_vibration_mms DOUBLE PRECISION,
    avg_peak_g DOUBLE PRECISION,
    avg_spindle_temp_c DOUBLE PRECISION,
    max_spindle_temp_c DOUBLE PRECISION,
    avg_rpm DOUBLE PRECISION,
    avg_load_pct DOUBLE PRECISION,
    parts_produced DOUBLE PRECISION,
    parts_per_hour DOUBLE PRECISION,
    latest_status VARCHAR(16),
    health_index DOUBLE PRECISION CHECK (health_index BETWEEN 0 AND 100),
    reading_count INTEGER NOT NULL DEFAULT 0 CHECK (reading_count >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_rt_window_metrics_machine_size_start UNIQUE (machine_id, window_size, window_start),
    CONSTRAINT chk_rt_window_metrics_range CHECK (window_end >= window_start)
);

CREATE INDEX IF NOT EXISTS idx_rt_window_metrics_machine_end ON rt_window_metrics (machine_id, window_end DESC);

CREATE TABLE IF NOT EXISTS rt_active_alerts (
